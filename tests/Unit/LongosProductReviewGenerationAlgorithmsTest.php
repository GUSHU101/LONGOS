<?php

namespace Tests\Unit;

use PHPUnit\Framework\TestCase;
use Plugin\LongosProductReviews\Services\GeneratedReviewContentPolicy;
use Plugin\LongosProductReviews\Services\ReviewGenerationLimits;
use Plugin\LongosProductReviews\Services\ReviewGenerationService;
use ReflectionClass;

class LongosProductReviewGenerationAlgorithmsTest extends TestCase
{
    private ReviewGenerationService $service;

    protected function setUp(): void
    {
        parent::setUp();
        $this->service = (new ReflectionClass(ReviewGenerationService::class))->newInstanceWithoutConstructor();
    }

    public function test_balanced_rating_and_country_pools_cover_values_evenly(): void
    {
        $ratings = $this->invoke('ratings', 12, 2, 5, 'balanced');
        $counts  = array_count_values($ratings);
        $covered = array_keys($counts);
        sort($covered);

        self::assertSame([2, 3, 4, 5], $covered);
        self::assertLessThanOrEqual(1, max($counts) - min($counts));

        $countries    = $this->invoke('balancedPool', ['Japan', 'France', 'Canada'], 10);
        $countryCount = array_count_values($countries);
        self::assertCount(10, $countries);
        self::assertLessThanOrEqual(1, max($countryCount) - min($countryCount));
    }

    public function test_near_duplicate_fingerprint_catches_light_rewrites_without_blocking_distinct_copy(): void
    {
        $original = $this->invoke('fingerprint', 'Secure lid. The compact bottle fits neatly in my work bag and is straightforward to rinse each evening.');
        $rewrite  = $this->invoke('fingerprint', 'Secure lid! The compact bottle fits neatly in my daily bag and is straightforward to rinse each evening.');
        $distinct = $this->invoke('fingerprint', 'Muted colors and a narrow silhouette give the exterior a clean, understated appearance.');

        self::assertTrue($this->invoke('isNearDuplicate', $rewrite, [$original]));
        self::assertFalse($this->invoke('isNearDuplicate', $distinct, [$original]));
    }

    public function test_maximum_batch_size_builds_complete_balanced_pools(): void
    {
        $count     = ReviewGenerationLimits::MAX_REVIEWS_PER_BATCH;
        $ratings   = $this->invoke('ratings', $count, 1, 5, 'balanced');
        $countries = $this->invoke('balancedPool', ['United States', 'Canada', 'Japan'], $count);

        self::assertSame(500, $count);
        self::assertCount(500, $ratings);
        self::assertCount(500, $countries);
        $coveredRatings = array_values(array_unique($ratings));
        sort($coveredRatings);
        self::assertSame([1, 2, 3, 4, 5], $coveredRatings);
    }

    public function test_generated_content_policy_rejects_creation_disclosures_in_supported_languages(): void
    {
        $policy  = new GeneratedReviewContentPolicy;
        $blocked = [
            'This review was generated by AI.',
            'This review was A.I. generated.',
            'AI reviewer content.',
            'Source: merchant',
            'Merchant-provided content for this product.',
            '这是一条由AI生成的评论。',
            '这是一条由ＡＩ生成的评论。',
            '来源：商家',
            '这是一条商家自定义评论。',
            'Diese KI-generierte Rezension ist ein Beispiel.',
            'Cet avis a été généré par une IA.',
            'Esta reseña fue generada por una IA.',
            'これはAIによって生成されたレビューです。',
        ];

        foreach ($blocked as $body) {
            self::assertSame(GeneratedReviewContentPolicy::VIOLATION_META, $policy->violation('Alex', 'Useful product', $body), $body);
        }
        self::assertSame(
            GeneratedReviewContentPolicy::VIOLATION_FORMATTING,
            $policy->violation('Alex', '**Useful product**', 'A clean and compact shape.'),
        );
        self::assertSame(
            GeneratedReviewContentPolicy::VIOLATION_CONTACT,
            $policy->violation('Alex', 'Contact me', 'Email alex@example.test or call +1 (555) 123-4567.'),
        );
        self::assertNull($policy->violation(
            'Alex Morgan',
            'Compact and practical',
            'The narrow shape fits neatly in a side pocket, and the muted finish looks understated.',
        ));
    }

    private function invoke(string $method, mixed ...$arguments): mixed
    {
        $reflection = new \ReflectionMethod($this->service, $method);

        return $reflection->invoke($this->service, ...$arguments);
    }
}

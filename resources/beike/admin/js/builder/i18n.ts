/** Chinese presentation for imported Shopify labels and raw schema identifiers. */
export const zhBuilderLabel = (value: unknown, fallback = "配置项"): string => {
  const source = typeof value === "string" ? value.trim() : "";
  if (!source) return fallback;
  return labels[source] || labels[source.replace(/^shopify-/, "")] || `配置项：${source}`;
};

